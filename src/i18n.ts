export function getHtmlLang(locale: Locale): string {
  switch (locale) {
    case "zh-CN":
      return "zh-Hans";
    case "ja":
      return "ja";
    case "en":
      return "en";
    default:
      return "zh-Hant";
  }
}

export function getApiLang(locale: Locale): string {
  switch (locale) {
    case "zh-CN":
      return "zh-cn";
    case "ja":
      return "ja-jp";
    case "en":
      return "en-us";
    default:
      return "zh-tw";
  }
}

