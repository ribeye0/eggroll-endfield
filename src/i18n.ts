export function getHtmlLang(locale: Locale): string {
  switch (locale) {
    case "zh-CN":
      return "zh-Hans";
    case "ja":
      return "ja";
    case "en":
      return "en";
    case "ko":
      return "ko";
    default:
      return "zh-Hant";
  }
}

